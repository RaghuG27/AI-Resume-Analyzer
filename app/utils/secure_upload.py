import os
import uuid
import zipfile

from pathlib import Path

from fastapi import HTTPException, UploadFile


MAX_FILE_SIZE = 10 * 1024 * 1024
CHUNK_SIZE = 1024 * 1024

# Keep uploads outside frontend public/static directories.
PROJECT_ROOT = Path(__file__).resolve().parents[2]
UPLOAD_DIR = PROJECT_ROOT / "uploads"

ALLOWED_EXTENSIONS = {".pdf", ".docx"}


def validate_file_content(path: Path, extension: str) -> None:
    with path.open("rb") as file:
        signature = file.read(8)

    if extension == ".pdf":
        if not signature.startswith(b"%PDF-"):
            raise HTTPException(
                status_code=415,
                detail="File content is not a valid PDF.",
            )

    elif extension == ".docx":
        if not signature.startswith(b"PK"):
            raise HTTPException(
                status_code=415,
                detail="File content is not a valid DOCX document.",
            )

        try:
            with zipfile.ZipFile(path) as archive:
                names = set(archive.namelist())

                if (
                    "[Content_Types].xml" not in names
                    or "word/document.xml" not in names
                ):
                    raise HTTPException(
                        status_code=415,
                        detail="Invalid DOCX document structure.",
                    )

                # Reject archive entries that could escape the document.
                for name in names:
                    member_path = Path(name)
                    if member_path.is_absolute() or ".." in member_path.parts:
                        raise HTTPException(
                            status_code=415,
                            detail="Invalid DOCX archive paths.",
                        )

        except zipfile.BadZipFile as exc:
            raise HTTPException(
                status_code=415,
                detail="Invalid DOCX archive.",
            ) from exc


async def save_resume_upload(
    upload: UploadFile,
) -> tuple[str, str]:
    original_name = Path(upload.filename or "").name
    extension = Path(original_name).suffix.lower()

    if extension not in ALLOWED_EXTENSIONS:
        raise HTTPException(
            status_code=415,
            detail="Only PDF and DOCX files are allowed.",
        )
    
    UPLOAD_DIR.mkdir(parents=True, exist_ok=True)

    # The stored name is generated by the server, not the user.
    stored_name = f"{uuid.uuid4().hex}{extension}"
    destination = UPLOAD_DIR / stored_name
    total_bytes = 0

    try:
        with destination.open("xb") as output:
            while True:
                chunk = await upload.read(CHUNK_SIZE)

                if not chunk:
                    break

                total_bytes += len(chunk)

                if total_bytes > MAX_FILE_SIZE:
                    raise HTTPException(
                        status_code=413,
                        detail="Resume exceeds the 10 MB size limit.",
                    )

                output.write(chunk)

        if total_bytes == 0:
            raise HTTPException(
                status_code=422,
                detail="Uploaded file is empty.",
            )

        validate_file_content(destination, extension)

        return stored_name, str(destination)

    except Exception:
        destination.unlink(missing_ok=True)
        raise

    finally:
        await upload.close()